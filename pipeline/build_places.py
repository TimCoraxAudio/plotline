"""Write the add-on's area backgrounds: addon/Plotline/Data/Places.lua.

The text is the zone and subzone lore Spoken Places reads when you enter an area
(`full` in Spoken's Data/enUS/Zones.lua and Subzones.lua). It comes from Warcraft Wiki
under CC BY-SA 4.0, adapted by Spoken, so the output file is CC BY-SA 4.0 too, not GPL,
and keeps each entry's source page (docs/LICENSING.md, "Area backgrounds").

Only entries with a Warcraft Wiki source are written. Spoken's entries with no source are
prose its own project wrote, which its MIT grant doesn't cover, so they stay out.

Run: uv run pipeline/build_places.py   (after: git submodule update --init --depth 1)
"""
import argparse, os, subprocess

from lupa import LuaRuntime

HERE = os.path.dirname(os.path.abspath(__file__))
SPOKEN = os.path.join(HERE, "sources", "spoken-wow")
OUT = os.path.join(HERE, "..", "addon", "Plotline", "Data", "Places.lua")
WIKI = "https://warcraft.wiki.gg/wiki/"


def load(spoken):
    """Spoken's English zone and subzone lore, plus where the client puts moved areas."""
    lua = LuaRuntime(unpack_returned_tuples=True)
    ns = lua.eval("""function()
        local ns = { data = {} }
        function ns:ShouldLoadLanguage(code) return code == "enUS" end
        function ns:RegisterLoreData(code, kind, data) self.data[kind] = data end
        return ns
    end""")()
    d = os.path.join(spoken, "addons", "Spoken_Places", "Data")
    for name in ("enUS/Zones.lua", "enUS/Subzones.lua", "AreaZones.lua"):
        lua.execute(open(os.path.join(d, name), encoding="utf-8").read(), "Spoken_Places", ns)
    return ns


def entry(e, skipped):
    """(text, page) for a usable entry, else None."""
    text = (e["full"] or "").strip()
    src = e["source"] or ""
    if e["pending"] or not text:
        return None
    if not src.startswith(WIKI):
        skipped.append(e["name"])
        return None
    return text, src[len(WIKI):]


def lua_str(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\n", "\\n") + '"'


def commit(path):
    try:
        return subprocess.run(["git", "-C", path, "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return "unknown"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--spoken", default=SPOKEN, help="spoken-wow checkout")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()

    ns = load(a.spoken)
    skipped = []
    zones = {}
    for map_id, e in ns["data"]["zones"].items():
        hit = entry(e, skipped)
        if hit:
            zones[int(map_id)] = hit
    areas = {}
    for map_id, t in ns["data"]["subzones"].items():
        for key, e in t.items():
            hit = entry(e, skipped)
            if hit:
                areas.setdefault(int(map_id), {})[key] = hit
    # areas whose story is kept under another zone than the one the client puts them in
    moved = {}
    for story, t in ns["AreaZones"].items():
        for key, where in t.items():
            if key not in areas.get(int(story), {}):
                continue
            maps = ([where["zone"]] if where["zone"] else []) + list((where["also"] or {}).values())
            for m in maps:
                moved.setdefault(int(m), {})[key] = int(story)

    out = [
        "-- SPDX-License-Identifier: CC-BY-SA-4.0",
        "-- Plotline: area backgrounds for the Journal's Places pages.",
        "-- GENERATED by pipeline/build_places.py. Do not edit by hand.",
        "--",
        "-- This file is NOT under Plotline's GPL. Its text is from Warcraft Wiki",
        "-- (https://warcraft.wiki.gg), by the contributors of each page named below, licensed under",
        "-- CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). It was adapted (page intros,",
        "-- trimmed to Classic) by Spoken (https://github.com/rusty-key/spoken-wow,"
        f" commit {commit(a.spoken)}),",
        "-- and Plotline only re-keys it. You may share and adapt it under the same licence, with",
        "-- attribution. Provided as is, without warranties. World of Warcraft names are Blizzard's.",
        "--",
        "-- zones[uiMapID] and areas[uiMapID][normalised subzone name] = { text, Warcraft Wiki page }.",
        "-- moved[uiMapID][name] = the map whose areas table holds that subzone.",
        "",
        "local _, ns = ...",
        "ns.places = { wiki = " + lua_str(WIKI) + ", zones = {}, areas = {}, moved = {} }",
        "local zones, areas, moved = ns.places.zones, ns.places.areas, ns.places.moved",
        "",
    ]
    for m, (text, page) in sorted(zones.items()):
        out.append(f"zones[{m}] = {{ {lua_str(text)}, {lua_str(page)} }}")
    out.append("")
    for m, t in sorted(areas.items()):
        out.append(f"areas[{m}] = {{")
        for key, (text, page) in sorted(t.items()):
            out.append(f"  [{lua_str(key)}] = {{ {lua_str(text)}, {lua_str(page)} }},")
        out.append("}")
    out.append("")
    for m, t in sorted(moved.items()):
        out.append(f"moved[{m}] = {{ " + ", ".join(f"[{lua_str(k)}] = {s}" for k, s in sorted(t.items())) + " }")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    n_areas = sum(len(t) for t in areas.values())
    print(f"wrote {os.path.relpath(a.out)}: {len(zones)} zones, {n_areas} subzones, "
          f"{sum(len(t) for t in moved.values())} moved; {len(skipped)} skipped (no wiki source)")


if __name__ == "__main__":
    main()
