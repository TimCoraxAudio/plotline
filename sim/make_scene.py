"""Write sim/PlotlineSim/Generated.lua: which scene PlotlineSim opens, and the quest titles it fakes.

By default titles are placeholders ("Quest 141"). With --real-text, titles and the dialog quest's text
come from EG Link (Blizzard's text): only for private screenshots, never commit the output
(Generated.lua is git-ignored).
"""
import argparse
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# "The Defias Brotherhood" and its side quest: the chain every scene shows.
QUESTS = [65, 132, 135, 141, 142, 155, 166, 214]


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'


def main():
    p = argparse.ArgumentParser()
    p.add_argument("scene")
    p.add_argument("--quest", type=int, default=141)
    p.add_argument("--real-text", action="store_true")
    p.add_argument("--eglink", default=os.path.join(ROOT, "pipeline", "sources", "eg-link-output-wowf"))
    p.add_argument("--out", default=os.path.join(HERE, "PlotlineSim", "Generated.lua"))
    a = p.parse_args()

    L = ["-- Generated by sim/make_scene.py. Git-ignored: may hold Blizzard text. Never commit.",
         "PlotlineSimConfig = {",
         f"  scene = {lua_str(a.scene)},",
         f"  quest = {a.quest},"]
    if a.real_text:
        eg = {}  # union across builds, newest last
        for f in sorted(glob.glob(os.path.join(a.eglink, "data", "wowf", "*", "quests.enUS.json"))):
            for k, v in json.load(open(f, encoding="utf-8"))["quests"].items():
                eg[int(k)] = v
        L.append("  titles = {")
        for q in sorted(set(QUESTS + [a.quest])):
            t = (eg.get(q) or {}).get("title")
            if t:
                L.append(f"    [{q}] = {lua_str(t)},")
        L.append("  },")
        r = eg.get(a.quest) or {}
        d, o = r.get("description"), r.get("objectivesText")
        if d:
            L.append(f"  text = {{ [{a.quest}] = {{ d = {lua_str(d)}, o = {lua_str(o or '')} }} }},")
    L.append("}")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"Wrote {a.out} (scene {a.scene}, {'real' if a.real_text else 'placeholder'} text)")


if __name__ == "__main__":
    main()
